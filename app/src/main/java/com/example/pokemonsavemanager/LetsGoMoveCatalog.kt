    private val byId = choices.associateBy { it.id }

    fun choice(id: Int): LetsGoMoveChoice? = byId[id]

    fun maximumPp(id: Int, ppUps: Int): Int {
        require(ppUps in 0..3) { "The preserved PP Up count must be between 0 and 3." }
        val base = choice(id)?.basePp ?: throw IllegalArgumentException("Move #$id is not available in Let's Go.")
        require(base > 0) { "Move #$id has no usable Let's Go PP value." }
        require(base > 4 || ppUps == 0) { "A 1-PP move cannot retain PP Ups." }
        return base + (base * ppUps / 5)
    }
